"""Collect every finished run into paper-ready tables, statistics and figures.

    python scripts/aggregate_results.py

Writes to results/tables/ and results/figures/, plus results/RESULTS.md:
  * main_comparison.{csv,tex}  mean ± std over folds (ours vs baselines)
  * ablation.{csv,tex}         one-change ablations vs ours
  * leakage.{csv,tex}          same models under grouped / random / augment-then-split
  * detection.{csv,tex}        stone detection (KidneyMTL vs detection-only vs YOLO)
  * pooled_oof.csv             pooled out-of-fold metrics with cluster-bootstrap 95% CIs
  * significance.csv           McNemar (ours vs each model), Holm-corrected
  * per_fold.csv               every summary.json row
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from sklearn.metrics import accuracy_score, f1_score  # noqa: E402

from src.config import load_config, resolve_path  # noqa: E402
from src.experiments import EXPERIMENTS, MAIN, protocol_of  # noqa: E402
from src.metrics import bootstrap_ci, classification_metrics, holm_correction, mcnemar_test, mean_std  # noqa: E402
from src.reporting import to_latex, to_markdown  # noqa: E402
from src.utils import load_json  # noqa: E402

CLS_METRICS = [("test_accuracy", "Acc"), ("test_balanced_accuracy", "Bal. Acc"), ("test_macro_f1", "Macro-F1"),
               ("test_macro_auc", "AUC"), ("test_mcc", "MCC"), ("test_stone_sensitivity", "Stone Sens."),
               ("test_stone_specificity", "Stone Spec."), ("test_ece", "ECE")]
DET_METRICS = [("det_mAP@0.5", "mAP@0.5"), ("det_mAP@0.5:0.95", "mAP@0.5:0.95"), ("det_precision@0.5", "P"),
               ("det_recall@0.5", "R"), ("det_f1@0.5", "F1")]


def fmt(vals, scale=100.0, digits=2):
    m, s = mean_std(vals)
    if np.isnan(m):
        return "-"
    return f"{scale * m:.{digits}f} ± {scale * s:.{digits}f}"


def label(name):
    return EXPERIMENTS.get(name, {}).get("label", name)


def collect(runs_root: Path) -> pd.DataFrame:
    rows = []
    for s in sorted(runs_root.glob("*/fold*/summary.json")):
        if not (s.parent / "DONE").exists() or not s.parent.name[4:].isdigit():
            continue  # skips archived fold<k>_stale_v<n> runs
        d = load_json(s)
        d["experiment"] = s.parent.parent.name
        d["run_dir"] = str(s.parent)
        rows.append(d)
    return pd.DataFrame(rows)


def summary_table(df, names, metrics):
    out = []
    for n in names:
        g = df[df.experiment == n]
        if g.empty:
            continue
        r = {"Model": label(n), "Folds": len(g)}
        for key, nice in metrics:
            r[nice] = fmt(g[key]) if key in g else "-"
        out.append(r)
    return pd.DataFrame(out)


def pooled_predictions(df, name):
    parts = [pd.read_csv(Path(r) / "test_predictions.csv").assign(fold=f)
             for r, f in zip(df.loc[df.experiment == name, "run_dir"], df.loc[df.experiment == name, "fold"])
             if (Path(r) / "test_predictions.csv").exists()]
    return pd.concat(parts, ignore_index=True) if parts else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", default="results/runs")
    ap.add_argument("--out", default="results")
    ap.add_argument("--bootstrap", type=int, default=None)
    args = ap.parse_args()

    cfg = load_config()
    classes = list(cfg.data.classes)
    runs_root = resolve_path(args.runs_root)
    out = resolve_path(args.out)
    tables, figs = out / "tables", out / "figures"
    tables.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    iters = args.bootstrap or cfg.eval.bootstrap_iters

    df = collect(runs_root)
    if df.empty:
        sys.exit(f"No finished runs under {runs_root}")
    df.to_csv(tables / "per_fold.csv", index=False)
    present = [n for n in EXPERIMENTS if n in set(df.experiment)]
    md = ["# Results summary (auto-generated by scripts/aggregate_results.py)\n"]

    # ------------------------------------------------------ main comparison
    names = [n for n in present if EXPERIMENTS[n]["group"] in ("main", "baselines")]
    t = summary_table(df, names, CLS_METRICS)
    if not t.empty:
        t.to_csv(tables / "main_comparison.csv", index=False)
        to_latex(t, tables / "main_comparison.tex",
                 "Four-class classification on CT-KIDNEY under the leakage-free grouped 5-fold protocol "
                 "(mean ± std over test folds, \\%).", "tab:main",
                 bold_best={c: ("min" if c == "ECE" else "max") for _, c in CLS_METRICS})
        md += ["## Main comparison (grouped CV)\n", to_markdown(t), ""]

    # ------------------------------------------------------------ ablation
    names = [MAIN] + [n for n in present if EXPERIMENTS[n]["group"] == "ablations"]
    abl_folds = sorted({f for n in names if n != MAIN for f in df.loc[df.experiment == n, "fold"]})
    sub = df[(df.experiment != MAIN) | (df.fold.isin(abl_folds))] if abl_folds else df
    t = summary_table(sub, [n for n in names if n in present], CLS_METRICS[:5] + [DET_METRICS[0]])
    if len(t) > 1:
        t.to_csv(tables / "ablation.csv", index=False)
        to_latex(t, tables / "ablation.tex",
                 f"Ablation study (folds {abl_folds}; each row changes one component of KidneyMTL).",
                 "tab:ablation")
        md += ["## Ablations\n", to_markdown(t), ""]

    # ------------------------------------------------------------- leakage
    families = {"KidneyMTL": (MAIN, "l_random_kidneymtl", "l_augsplit_kidneymtl"),
                "ResNet-50": ("b_resnet50", "l_random_resnet50", "l_augsplit_resnet50"),
                "CDR-VGG19": ("b_cdr_vgg19", "l_random_cdr_vgg19", "l_augsplit_cdr_vgg19")}
    rows = []
    for fam, exps in families.items():
        r = {"Model": fam}
        for proto, e in zip(("Grouped (ours)", "Random image split", "Augment-then-split (ref.)"), exps):
            g = df[df.experiment == e]
            r[f"{proto} Acc"] = fmt(g["test_accuracy"]) if len(g) else "-"
            r[f"{proto} F1"] = fmt(g["test_macro_f1"]) if len(g) else "-"
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(tables / "leakage.csv", index=False)
    to_latex(t, tables / "leakage.tex", "Effect of the evaluation protocol on reported performance (\\%).",
             "tab:leakage")
    md += ["## Leakage study\n", to_markdown(t), ""]
    rep = resolve_path(cfg.data.splits_dir) / "leakage_report.json"
    if rep.exists():
        md += ["Split audit (`data/splits/leakage_report.json`):\n", "```", rep.read_text(), "```", ""]
    _leakage_figure(df, families, figs / "leakage.png")

    # ----------------------------------------------------------- detection
    names = [n for n in present if any(k in df.columns and df.loc[df.experiment == n, k].notna().any()
                                       for k, _ in DET_METRICS[:1])]
    t = summary_table(df, names, DET_METRICS)
    for y in sorted(runs_root.glob("yolo_*/metrics.json")):
        d = load_json(y)
        t = pd.concat([t, pd.DataFrame([{"Model": d.get("label", y.parent.name), "Folds": 1,
                                         **{nice: f"{100 * d[k]:.2f}" if k in d else "-"
                                            for k, nice in DET_METRICS}}])], ignore_index=True)
    if not t.empty:
        t.to_csv(tables / "detection.csv", index=False)
        to_latex(t, tables / "detection.tex", "Kidney-stone detection on the Dataset-1 test split (\\%).",
                 "tab:detection", bold_best={"mAP@0.5": "max", "mAP@0.5:0.95": "max"})
        md += ["## Stone detection\n", to_markdown(t), ""]

    # ------------------------------------------------- external validation
    if "ext_stone_sensitivity" in df:
        names = [n for n in present if df.loc[df.experiment == n, "ext_stone_sensitivity"].notna().any()]
        t = summary_table(df, names, [("ext_stone_sensitivity", "Stone sensitivity"),
                                      ("ext_stone_in_top2", "Stone in top-2"), ("ext_mean_p_stone", "Mean P(stone)")])
        if not t.empty:
            t.to_csv(tables / "external_validation.csv", index=False)
            to_latex(t, tables / "external_validation.tex",
                     "External cross-dataset, cross-view test: classifiers trained on axial CT-KIDNEY applied to "
                     "the unseen coronal Dataset-1 test split (all images contain stones; \\%).",
                     "tab:external", bold_best={"Stone sensitivity": "max"})
            md += ["## External validation (Dataset-1 test, coronal)\n", to_markdown(t), ""]

    # ----------------------------------- pooled OOF + bootstrap + McNemar
    pooled_rows, sig_rows = [], []
    main_pred = pooled_predictions(df, MAIN) if MAIN in present else None
    for n in present:
        if EXPERIMENTS[n]["group"] == "detection":
            continue
        p = pooled_predictions(df, n)
        if p is None:
            continue
        probs = p[[f"prob_{c}" for c in classes]].values
        y = p["label"].values
        m = classification_metrics(y, probs, classes)
        groups = p["group"].values if "group" in p and protocol_of(n) != "aug_then_split" else None
        acc_ci = bootstrap_ci(y, probs, lambda a, b: accuracy_score(a, b.argmax(1)), iters, groups=groups)
        f1_ci = bootstrap_ci(y, probs, lambda a, b: f1_score(a, b.argmax(1), average="macro"), iters,
                             groups=groups)
        pooled_rows.append({"Model": label(n), "experiment": n, "protocol": protocol_of(n), "n": len(p),
                            "folds": p["fold"].nunique(),
                            "Acc": f"{100 * m['accuracy']:.2f} [{100 * acc_ci[0]:.2f}, {100 * acc_ci[1]:.2f}]",
                            "Macro-F1": f"{100 * m['macro_f1']:.2f} [{100 * f1_ci[0]:.2f}, {100 * f1_ci[1]:.2f}]",
                            "AUC": f"{100 * m.get('macro_auc', float('nan')):.2f}",
                            "ECE": f"{100 * m['ece']:.2f}"})
        if main_pred is not None and n != MAIN and protocol_of(n) == "grouped":
            mg = main_pred.merge(p, on="path", suffixes=("_a", "_b"))
            if len(mg):
                r = mcnemar_test(mg["pred_a"].values == mg["label_a"].values,
                                 mg["pred_b"].values == mg["label_b"].values)
                sig_rows.append({"comparison": f"{label(MAIN)} vs {label(n)}", "experiment": n,
                                 "group": EXPERIMENTS[n]["group"], "n_paired": len(mg),
                                 "acc_ours": (mg["pred_a"] == mg["label_a"]).mean(),
                                 "acc_other": (mg["pred_b"] == mg["label_b"]).mean(), **r})
    if pooled_rows:
        t = pd.DataFrame(pooled_rows)
        t.to_csv(tables / "pooled_oof.csv", index=False)
        md += ["## Pooled out-of-fold metrics (95% cluster-bootstrap CI)\n",
               to_markdown(t.drop(columns=["experiment"])), ""]
    if sig_rows:
        s = pd.DataFrame(sig_rows)
        for grp, idx in s.groupby("group").groups.items():
            s.loc[idx, "p_holm"] = holm_correction(s.loc[idx, "p_value"].tolist())
        s.to_csv(tables / "significance.csv", index=False)
        show = s[["comparison", "n_paired", "acc_ours", "acc_other", "p_value", "p_holm"]].copy()
        for c in ("acc_ours", "acc_other"):
            show[c] = (100 * show[c]).map(lambda v: f"{v:.2f}")
        for c in ("p_value", "p_holm"):
            show[c] = show[c].map(lambda v: f"{v:.2e}")
        to_latex(show, tables / "significance.tex",
                 "Exact McNemar tests on paired out-of-fold predictions (Holm-corrected within each group).",
                 "tab:significance")
        md += ["## Significance (McNemar, Holm-corrected)\n", to_markdown(show), ""]

    _comparison_figure(df, [n for n in present if EXPERIMENTS[n]["group"] in ("main", "baselines")],
                       figs / "main_comparison.png")
    (out / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"\nTables -> {tables}\nFigures -> {figs}")


def _leakage_figure(df, families, path):
    protos = ["Grouped\n(ours)", "Random\nimage split", "Augment-then-\nsplit (ref.)"]
    fig, ax = plt.subplots(figsize=(6, 3.4))
    w = 0.25
    colors = ["#2a6fdb", "#e0533d", "#27a35a"]
    any_bar = False
    for i, (fam, exps) in enumerate(families.items()):
        means, stds = [], []
        for e in exps:
            m, s = mean_std(df.loc[df.experiment == e, "test_macro_f1"]) if (df.experiment == e).any() else (
                np.nan, np.nan)
            means.append(100 * m)
            stds.append(100 * s)
        if not np.all(np.isnan(means)):
            any_bar = True
        ax.bar(np.arange(3) + (i - 1) * w, means, w, yerr=stds, label=fam, color=colors[i], capsize=2)
    if not any_bar:
        plt.close(fig)
        return
    ax.set_xticks(range(3), protos)
    ax.set_ylabel("test macro-F1 (%)")
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


def _comparison_figure(df, names, path):
    if not names:
        return
    vals = [100 * df.loc[df.experiment == n, "test_macro_f1"].values for n in names]
    fig, ax = plt.subplots(figsize=(max(4, 1.1 * len(names)), 3.4))
    ax.boxplot(vals, showmeans=True)
    ax.set_xticks(range(1, len(names) + 1), [label(n) for n in names], rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("test macro-F1 (%) per fold")
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


if __name__ == "__main__":
    main()
